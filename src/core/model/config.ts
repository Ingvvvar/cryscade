export type SpinMode = 'base' | 'free';

export interface GameConfig {
  /** Наименьший кластер. */
  readonly clusterMin: number;
  /** Нижние границы полос размеров по возрастанию; первая равна clusterMin, последняя открыта сверху. */
  readonly sizeBands: readonly number[];
  /** Выплаты в сотых долях ставки: [символ 0…6][полоса]. */
  readonly paytableX100: readonly (readonly number[])[];
  /** Веса символов 0…7 по режимам; символ и досыпка берутся из распределения своего режима. */
  readonly weights: Readonly<Record<SpinMode, readonly number[]>>;
  /** Фриспины за ядра в конце основного спина: индекс — число ядер, последний элемент — для всех больших. */
  readonly freeSpinsByScatters: readonly number[];
  /** Ретриггер: не меньше min ядер за фриспин — ещё add спинов. */
  readonly retrigger: { readonly min: number; readonly add: number };
  /** Кап раунда в сотых долях ставки. */
  readonly capX100: number;
}

