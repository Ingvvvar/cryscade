// Часы кадра (§8.2, §10): единственное место, где дробное время тикера становится целыми миллисекундами. Тикер приходит
// ссылкой — дробное deltaMS читается здесь и не пересекает ни одного вызова: на вызове невстроенной функции V8 упаковал
// бы его в кучу. Дробный остаток копится в Float64Array, наружу — целые мс: сумма целых отстаёт от суммы дельт меньше
// чем на миллисекунду, дрейфа нет. Дальше по пути кадра — часы декора, часы показа, sampleScene — идут только целые.

/** Что часам кадра нужно от тикера: время прошедшего кадра в дробных миллисекундах — Ticker Pixi подходит как есть. */
export interface FrameTicker {
  readonly deltaMS: number;
}

export class FrameClock {
  /** Дробный остаток, мс: от 0 до 1. */
  readonly #carry = new Float64Array(1);

  /** Целые миллисекунды кадра: целая часть накопленного времени; остаток ждёт следующих кадров. */
  advance(ticker: FrameTicker): number {
    const total = (this.#carry[0] ?? 0) + ticker.deltaMS;
    const whole = Math.floor(total);
    this.#carry[0] = total - whole;
    return whole;
  }
}
